const SUBST: Record<string, string> = { "½": "1/2", "–": "-", "—": "-", "…": "..." };

/** Run-length path for the string (one unit per font pixel) and its width. */
function layout(text: string): { d: string; w: number } {
  const chars = [...text.toUpperCase()].map((c) => SUBST[c] ?? c).join("");
  let x = 0;
  let d = "";
  for (const ch of chars) {
    const g = GLYPHS[ch] ?? GLYPHS[" "];
    g.forEach((row, y) => {
      for (let i = 0; i < row.length; ) {
        if (row[i] !== "#") {
          i += 1;
          continue;
        }
        let j = i;
        while (row[j] === "#") j += 1;
        d += `M${x + i} ${y}h${j - i}v1h${i - j}z`;
        i = j;
      }
    });
    x += g[0].length + 1;
  }
  return { d, w: Math.max(1, x - 1) };
}

/**
 * Text in a hard 5×7 bitmap font, as crisp SVG rects with a one-pixel drop
 * shadow. One font pixel is `--pt` CSS px (default 2px); colour comes from
 * `color`, the shadow from `--pixel-shadow`.
 */
export function PixelText({ text, className = "" }: { text: string; className?: string }) {
  const { d, w } = useMemo(() => layout(text), [text]);
  return (
    <svg
      className={`pixel-text ${className}`.trim()}
      viewBox={`0 0 ${w + 1} 8`}
      style={{ width: `calc(${w + 1} * var(--pt, 2px))`, height: `calc(8 * var(--pt, 2px))` }}
      shapeRendering="crispEdges"
      role="img"
      aria-label={text}
    >
      <path className="pixel-text__shadow" d={d} transform="translate(1 1)" />
      <path d={d} fill="currentColor" />
    </svg>
  );
}
